"""M4 smoke test: inner-loop artifact generation (issue branben/school-core#163).

Verifies that `source.json` and `pr-writeup.html` are generated by the inner
loop AND committed into the PR branch so they appear in the PR diff:

1. `_generate_inner_loop_artifacts` runs the real generator scripts against a
   temp repo and produces `docs/source.json`, `docs/pr-writeup.md`, and
   `docs/pr-writeup.html`.
2. `create_pr_for_issue` commits those generated artifacts into the PR commit
   tree (GitHub API tree POST), so `source.json` / `pr-writeup.html` appear in
   the PR diff.
3. A real git diff carrying `source.json` passes `review_gate.py` check #5
   (inner-loop chain of custody), matching the M4 success criterion.

Run: python -m pytest tests/test_m4_inner_loop_smoke.py -v
"""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path
from unittest.mock import patch

import pytest

import issue_bridge
from issue_bridge import _generate_inner_loop_artifacts, _inner_loop_artifact_map
from src.bridge.pr_creator import create_pr_for_issue

REPO_ROOT = Path(__file__).resolve().parents[1]


def _git(repo: Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        ["git", "-C", str(repo), *args],
        check=True, capture_output=True, text=True,
    )


@pytest.fixture
def inner_loop_repo(tmp_path):
    """A temp repo with the four prior inner-loop artifacts + a spec file."""
    repo = tmp_path / "repo"
    repo.mkdir()
    _git(repo, "init", "-q")
    _git(repo, "config", "user.email", "test@example.com")
    _git(repo, "config", "user.name", "Test User")
    (repo / "README.md").write_text("base\n", encoding="utf-8")
    docs = repo / "docs"
    docs.mkdir()
    for name in ("prime-module-map.html", "plan-tweakable.html", "dev-log.md", "validate-prototype.html"):
        (docs / name).write_text(f"<html>{name}</html>\n" if name.endswith(".html") else f"# {name}\n",
                                 encoding="utf-8")
    spec = tmp_path / "spec.md"
    spec.write_text(
        "## Acceptance criteria\n\n- AC1: source.json generated\n- AC2: pr-writeup.html rendered\n",
        encoding="utf-8",
    )
    _git(repo, "add", ".")
    _git(repo, "commit", "-qm", "base: prior inner-loop artifacts")
    return repo


def test_artifacts_generated_for_real(inner_loop_repo):
    """Real generators produce source.json + pr-writeup.md/.html."""
    repo = inner_loop_repo
    spec_rel = "docs/plans/2026-11-01-001-full-inner-loop-walk-plan.md"
    spec_abs = repo / spec_rel
    spec_abs.parent.mkdir(parents=True, exist_ok=True)
    spec_abs.write_text(
        "## Milestone 1\n\n## Acceptance criteria\n\n- AC1: payload embedded\n- AC2: offline works\n",
        encoding="utf-8",
    )
    issue = {"bd_id": "school-core-yexd", "title": "M4 smoke", "number": 163}
    task_result = {
        "spec": spec_rel,
        "bead": "school-core-yexd",
    }
    review_evidence = {
        "cto_verdict": "PASS", "coo_verdict": "PASS", "combined_score": 90.0,
        "accepted": True, "decisions": ["D1"],
        "verify_result": {"verdict": "PASS", "passed": True},
    }

    _generate_inner_loop_artifacts(
        repo_path=repo,
        issue=issue,
        task_result=task_result,
        review_evidence=review_evidence,
        verify_result={"passed": True},
        pr_number=163,
        pr_title="M4 smoke test",
    )

    source = repo / "docs" / "source.json"
    assert source.is_file(), "source.json must be generated"
    payload = json.loads(source.read_text(encoding="utf-8"))
    assert payload["bead"] == "school-core-yexd"
    assert payload["decisions"] == ["D1"]
    assert len(payload["artifacts"]) == 4

    writeup_md = repo / "docs" / "pr-writeup.md"
    writeup_html = repo / "docs" / "pr-writeup.html"
    assert writeup_md.is_file(), "pr-writeup.md must be generated"
    assert writeup_html.is_file(), "pr-writeup.html must be generated"
    assert "<html" in writeup_html.read_text(encoding="utf-8").lower()


def test_artifact_map_reflects_generated_files(inner_loop_repo):
    """_inner_loop_artifact_map returns the file set that production passes on."""
    repo = inner_loop_repo
    assert _inner_loop_artifact_map(repo) == {}
    (repo / "docs" / "source.json").write_text("{}", encoding="utf-8")
    assert _inner_loop_artifact_map(repo) == {"docs/source.json": str(repo / "docs" / "source.json")}


class TestPrDiffIncludesArtifacts:
    """M4 success criterion: source.json + pr-writeup.html appear in the PR diff."""

    def _mock_api_flow(self, mock_api, artifact_blob_shas):
        """The full GitHub API call sequence for create_pr_for_issue, with an
        extra blob POST per generated artifact."""
        calls = [
            None,  # branch does not exist yet (GET check)
            {"ref": "refs/heads/school/issue-163-m4-smoke-test"},
            {"object": {"sha": "branchsha456"}},
            {"sha": "basetree789"},
            {"sha": "outblob111"},                       # output.md
            *[{"sha": s} for s in artifact_blob_shas],   # artifact blobs
            {"sha": "newtree222"},
            {"sha": "newcommit333"},
            {"ref": "refs/heads/school/issue-163-m4-smoke-test"},
        ]
        mock_api.side_effect = calls

    @patch("src.bridge.pr_creator._gh_api")
    @patch("src.bridge.pr_creator._gh")
    def test_tree_post_carries_generated_docs_artifacts(self, mock_gh, mock_api, tmp_path, inner_loop_repo):
        repo = inner_loop_repo
        # Create real generated artifacts.
        (repo / "docs" / "source.json").write_text(
            json.dumps({"bead": "school-core-yexd", "spec": "x", "decisions": ["D1"],
                        "artifacts": [], "spec_acceptance": "- AC1\n"}), encoding="utf-8")
        (repo / "docs" / "pr-writeup.md").write_text("# Writeup\n", encoding="utf-8")
        (repo / "docs" / "pr-writeup.html").write_text("<html>writeup</html>\n", encoding="utf-8")

        artifacts = _inner_loop_artifact_map(repo)

        mock_gh.side_effect = [
            json.dumps({"defaultBranch": "main"}),
            "basesha123\n",
            "https://github.com/user/test/pull/163",
        ]
        # Blob shas are consumed in sorted-target order (pr-writeup.html,
        # pr-writeup.md, source.json) because create_pr_for_issue iterates
        # sorted(inner_loop_artifacts.items()).
        self._mock_api_flow(mock_api, artifact_blob_shas=["wuphtml3", "wupmd2", "srcblob1"])

        issue = {"issue_number": 163, "title": "M4 smoke test", "domain": "debugging", "difficulty": "easy"}
        task_result = {"response": "print('ok')\n", "agent": "owl-alpha"}
        url = create_pr_for_issue(
            issue, task_result, "user/test", work_dir=str(tmp_path),
            inner_loop_artifacts=artifacts,
        )
        assert url == "https://github.com/user/test/pull/163"

        tree_post = next(
            c for c in mock_api.call_args_list
            if c.args and c.args[0] == "POST" and "trees" in c.args[1]
        )
        paths = {e["path"] for e in tree_post.args[2]["tree"]}
        assert "docs/source.json" in paths
        assert "docs/pr-writeup.md" in paths
        assert "docs/pr-writeup.html" in paths

        # Blob shas flow through to the tree entries.
        entries = {e["path"]: e["sha"] for e in tree_post.args[2]["tree"]}
        assert entries["docs/source.json"] == "srcblob1"
        assert entries["docs/pr-writeup.html"] == "wuphtml3"

    @patch("src.bridge.pr_creator._gh_api")
    @patch("src.bridge.pr_creator._gh")
    def test_missing_local_artifact_is_skipped(self, mock_gh, mock_api, tmp_path):
        """A map entry whose local file vanished must not break the PR."""
        missing = tmp_path / "missing" / "source.json"
        assets = {"docs/source.json": str(missing), "docs/pr-writeup.html": str(tmp_path / "nohtml.html")}
        mock_gh.side_effect = [
            json.dumps({"defaultBranch": "main"}),
            "basesha123\n",
            "https://github.com/user/test/pull/164",
        ]
        # Only the output blob is created; both artifact entries are skipped.
        self._mock_api_flow(mock_api, artifact_blob_shas=[])

        issue = {"issue_number": 164, "title": "Missing artifacts", "domain": "debugging", "difficulty": "easy"}
        task_result = {"response": "print('ok')\n", "agent": "owl-alpha"}
        url = create_pr_for_issue(issue, task_result, "user/test", inner_loop_artifacts=assets)
        assert url == "https://github.com/user/test/pull/164"


def test_bridge_artifact_map_wired_into_pr_creation():
    """The direct-path PR call passes the generated artifact map through."""
    import ast
    source = Path(issue_bridge.__file__).read_text(encoding="utf-8")
    tree = ast.parse(source)
    sel = [
        n for n in ast.walk(tree)
        if isinstance(n, ast.Call)
        and isinstance(n.func, ast.Name)
        and n.func.id == "create_pr_for_issue"
    ]
    assert sel, "expected a create_pr_for_issue call in issue_bridge.py"
    assert any(
        isinstance(kw.arg, str) and kw.arg == "inner_loop_artifacts"
        for call in sel for kw in call.keywords
    ), "the bridge must forward inner_loop_artifacts to create_pr_for_issue"


class TestReviewGateSourceBlockOnGeneratedArtifacts:
    """review_gate.py check #5 passes when a PR diff carries the generated chain."""

    def test_source_block_passes_on_docs_only_pr(self, tmp_path):
        repo = tmp_path / "repo"
        repo.mkdir()
        _git(repo, "init", "-q")
        _git(repo, "config", "user.email", "t@t.t")
        _git(repo, "config", "user.name", "t")
        (repo / "README.md").write_text("base\n", encoding="utf-8")
        _git(repo, "add", ".")
        _git(repo, "commit", "-qm", "base")

        docs = repo / "docs"
        docs.mkdir()
        for name in ("prime-module-map.html", "plan-tweakable.html", "dev-log.md", "validate-prototype.html"):
            (docs / name).write_text(f"<html>{name}</html>\n", encoding="utf-8")
        source = {
            "bead": "school-core-yexd",
            "spec": "docs/plans/2026-11-01-001-full-inner-loop-walk-plan.md · M4",
            "decisions": ["D1"],
            "artifacts": [
                "docs/prime-module-map.html",
                "docs/plan-tweakable.html",
                "docs/dev-log.md",
                "docs/validate-prototype.html",
            ],
            "spec_acceptance": "- AC1: source.json generated\n- AC2: pr-writeup.html rendered\n",
        }
        (docs / "source.json").write_text(json.dumps(source, indent=2) + "\n", encoding="utf-8")
        (docs / "pr-writeup.html").write_text("<html>writeup</html>\n", encoding="utf-8")

        _git(repo, "add", ".")
        _git(repo, "commit", "-qm", "add generated inner-loop artifacts school-core-yexd")

        gate = subprocess.run(
            [sys.executable, str(REPO_ROOT / "scripts" / "review_gate.py"),
             "--base", "HEAD~1", "--head", "HEAD", "--json"],
            cwd=repo, capture_output=True, text=True,
        )
        data = json.loads(gate.stdout)
        assert gate.returncode == 0, data
        assert data["pass"] is True
        assert not any(f["check"] == "source-block" for f in data["failures"])