"""Regression: run_verify_gate must copy node_modules without hardlinking.

The cached clone is shared across verification cycles. Hardlinking untrusted
installed packages would let an executed test mutate the shared cache.
"""

from pathlib import Path
from types import SimpleNamespace

import verify_gate


def _make_pnpm_repo(root: Path) -> Path:
    repo = root / "repo"
    nm = repo / "node_modules"
    (nm / ".pnpm" / "vitest@1.0.0").mkdir(parents=True)
    (nm / ".pnpm" / "vitest@1.0.0" / "index.js").write_text("module.exports={}\n")
    (repo / "package.json").write_text('{"name":"x","scripts":{"lint":"true"}}\n')
    (repo / "src").mkdir()
    (repo / "src" / "a.ts").write_text("export const a = 1\n")
    return repo


def test_node_modules_is_copied_to_scratch_without_hardlinks(monkeypatch, tmp_path):
    repo = _make_pnpm_repo(tmp_path)
    original = repo / "node_modules" / ".pnpm" / "vitest@1.0.0" / "index.js"
    captured = {}

    def fake_run(command, **kwargs):
        copied = Path(kwargs["cwd"]) / "node_modules" / ".pnpm" / "vitest@1.0.0" / "index.js"
        captured["exists"] = copied.is_file()
        captured["same_inode"] = copied.stat().st_ino == original.stat().st_ino
        copied.write_text("tampered by verify command")
        output = "__SCHOOL_VERIFY_START_0__\n__SCHOOL_VERIFY_END_0__0\n"
        return verify_gate.subprocess.CompletedProcess(command, 0, output, "")

    monkeypatch.setattr(verify_gate, "_find_nix", lambda: "/usr/bin/true")
    monkeypatch.setattr(verify_gate, "sandbox_exec_path", lambda: "/usr/bin/true")
    monkeypatch.setattr(verify_gate.subprocess, "run", fake_run)
    monkeypatch.setattr(verify_gate, "_flake_ref", lambda _: tmp_path)
    monkeypatch.setattr(verify_gate, "_discover_commands", lambda *a, **k: [{"cmd": "true", "cwd": "."}])
    (tmp_path / "flake.nix").write_text("{}\n")
    # Supervisor freezes the contract before the candidate runs (candidate
    # manifests are untrusted); the gate requires it.
    contract = verify_gate.freeze_verification_contract(repo)

    result = verify_gate.run_verify_gate(repo, flake_path=tmp_path, trusted_contract=contract)

    assert result["passed"] is True
    assert captured == {"exists": True, "same_inode": False}
    assert original.read_text() == "module.exports={}\n"


def test_node_modules_over_copy_limit_skips(tmp_path, monkeypatch):
    repo = _make_pnpm_repo(tmp_path)
    monkeypatch.setattr(verify_gate, "_find_nix", lambda: "/usr/bin/true")
    monkeypatch.setattr(verify_gate, "sandbox_exec_path", lambda: "/usr/bin/true")
    (tmp_path / "flake.nix").write_text("{}\n")
    real_rglob = Path.rglob

    class LargeFile:
        def is_file(self):
            return True

        def stat(self):
            return SimpleNamespace(st_size=501 * 1024 * 1024)

    def large_dependency_tree(self, pattern):
        if self.name == "node_modules":
            return iter([LargeFile()])
        return real_rglob(self, pattern)

    monkeypatch.setattr(Path, "rglob", large_dependency_tree)
    contract = verify_gate.freeze_verification_contract(repo)
    result = verify_gate.run_verify_gate(repo, flake_path=tmp_path, trusted_contract=contract)
    assert result["skipped"] is True
    assert "500MB" in result["failures"][0]["stderr"]
