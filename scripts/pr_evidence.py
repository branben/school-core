#!/usr/bin/env python3
"""Generate a PR verification section from measurements, not assertions.

A hand-typed checklist verifies what its author chose to test. It cannot tell
a reader whether the tests that exist would have caught a defect in the diff --
and it goes stale the moment the branch moves. This script produces the
opposite: every box is ticked by a measurement taken at run time, and every
line carries the evidence that decided it.

Two loops, linked:

  OUTER  CI runs for the PR's head SHA (gh run list --commit).
         This is the part a reviewer cannot fake, because GitHub owns it.

  INNER  The tests covering the changed modules, run locally against the
         checked-out tree. Each changed ``src/`` module is mapped to the test
         files that name it, so the report says which tests are *relevant to
         this diff* rather than which tests happen to pass.

The link is the point: an inner-loop claim is only interesting if the outer
loop agrees about the same commit.

Usage::

    python3 scripts/pr_evidence.py 160
    python3 scripts/pr_evidence.py 160 --post     # update the PR comment

Exit code is 0 when every checkable item passed, 1 otherwise, so this can
gate a merge without a human reading it.

Deliberately not a framework: no config file, no registry, no plugin points.
If the mapping rules below stop being true, change them here.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
COMMENT_MARKER = "<!-- pr-evidence:generated -->"

# Checks that exist on every PR and whose absence is a repo-config defect
# rather than a signal about this diff.
PHANTOM_CHECKS = {"circleci"}


@dataclass
class Check:
    """One line of the report."""

    label: str
    ok: bool
    detail: str
    link: str = ""

    def render(self) -> str:
        # No checkboxes. A ticked box is an assertion; "PASS" here means a
        # command ran and returned 0 at generation time, and the detail says
        # which command. A stale box cannot silently stay ticked.
        status = "PASS" if self.ok else "FAIL"
        text = f"- **{self.label}** — {status} — {self.detail}"
        if self.link:
            text += f" — {self.link}"
        return text


@dataclass
class Report:
    outer: list[Check] = field(default_factory=list)
    inner: list[Check] = field(default_factory=list)
    guards: list[Check] = field(default_factory=list)

    def ok(self) -> bool:
        return all(c.ok for c in self.outer + self.inner + self.guards)

    def render(self, pr: int, sha: str, branch: str) -> str:
        # Matches .github/PULL_REQUEST_TEMPLATE.md: [inner loop] Review, then
        # Feedback (the validate phase). Outer loop lives under Feedback
        # because "what actually executed" is the validate answer, and the
        # inner loop's own phases are the review.
        lines = [
            COMMENT_MARKER,
            "## [inner loop] Review",
            "",
            f"Head `{sha[:7]}` on `{branch}`. Every line below was set by a "
            "command run at generation time; none were typed by hand.",
            "",
            *(c.render() for c in self.inner),
            "",
            "**Guards**",
            "",
            *(c.render() for c in self.guards),
            "",
            "## Feedback",
            "",
            "Validate phase — what actually executed against this commit:",
            "",
            *(c.render() for c in self.outer),
            "",
            f"<sub>Generated by `scripts/pr_evidence.py {pr}`. "
            "Re-run it after pushing; a stale report is worse than none.</sub>",
        ]
        return "\n".join(lines)


def _run(cmd: list[str], **kw) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, capture_output=True, text=True, cwd=REPO_ROOT, **kw)


def _gh(*args: str) -> str:
    proc = _run(["gh", *args])
    if proc.returncode != 0:
        raise RuntimeError(f"gh {' '.join(args)} failed: {proc.stderr.strip()[:400]}")
    return proc.stdout


def pr_head(pr: int) -> tuple[str, str]:
    """Return (headRefOid, headRefName) for a PR."""
    raw = _gh(
        "pr", "view", str(pr), "--json", "headRefOid,headRefName",
        "-q", ".headRefOid + \" \" + .headRefName",
    ).strip()
    sha, _, branch = raw.partition(" ")
    return sha, branch


def outer_loop(sha: str) -> list[Check]:
    """CI conclusions for the PR's head commit -- owned by GitHub, not by us."""
    checks: list[Check] = []
    try:
        raw = _gh(
            "run", "list", "--commit", sha, "--limit", "20",
            "--json", "name,conclusion,status,url,workflowName",
        )
    except RuntimeError as exc:
        return [Check("CI runs", False, f"could not query runs: {exc}")]

    runs = json.loads(raw or "[]")
    if not runs:
        return [Check("CI runs", False, f"no workflow run found for {sha[:7]}")]

    # One line per workflow, worst conclusion wins.
    by_workflow: dict[str, dict] = {}
    for run in runs:
        name = run.get("workflowName") or run.get("name") or "workflow"
        prev = by_workflow.get(name)
        if prev is None or (run.get("conclusion") or "") > (prev.get("conclusion") or ""):
            by_workflow[name] = run

    for name, run in sorted(by_workflow.items()):
        conclusion = run.get("conclusion") or run.get("status") or "unknown"
        ok = conclusion == "success"
        detail = conclusion
        if name.lower() in PHANTOM_CHECKS and conclusion == "failure":
            detail = (
                "failure — no `.circleci/config.yml` in this repo, so this "
                "check can never pass (repo config, not this diff)"
            )
            # A phantom check is a real problem, but not one this PR introduced.
            # Report it unchecked so it stays visible without blocking the merge.
        checks.append(Check(name, ok, detail, run.get("url", "")))
    return checks


def changed_files(pr: int) -> list[str]:
    """Files changed by this PR, as GitHub reports them.

    Deliberately NOT `git diff merge-base origin/main`: a stale local
    ``origin/main`` ref makes that diff include every commit since the ref was
    last fetched, so the report attributes other branches' work to this PR.
    GitHub's own file list is authoritative and needs no fetch.
    """
    raw = _gh("pr", "diff", str(pr), "--name-only")
    return [line.strip() for line in raw.splitlines() if line.strip()]


def covering_tests(module_path: str) -> list[str]:
    """Test files that name this module's stem.

    Deliberately a name match, not an import graph: it is cheap, it is
    explainable, and it over-reports (a test mentioning the name counts) which
    is the safe direction -- it never claims coverage that isn't there.
    """
    stem = Path(module_path).stem
    if not stem or len(stem) < 3:
        return []
    proc = _run(
        ["grep", "-rl", "--include=test_*.py", stem, "tests/"],
    )
    if proc.returncode not in (0, 1):
        return []
    return sorted(
        line.strip() for line in proc.stdout.splitlines()
        if line.strip() and Path(line.strip()).exists()
    )


def run_tests(paths: list[str]) -> tuple[bool, str]:
    """Run the given test files and return (passed, summary).

    A run that produced no parseable summary is a FAILURE with a reason. The
    old fallback text, "no test summary produced", read like a formatting
    problem and hid pytest's exit code behind it: exit 4 is a usage error or
    nothing collected, exit 5 is no tests collected. Neither is "the report
    just didn't format" -- both mean nothing was verified.
    """
    unique = sorted(set(paths))
    if not unique:
        return False, "no tests"
    proc = _run(
        [
            sys.executable, "-m", "pytest", *unique, "-q",
            f"--basetemp=/tmp/pr-evidence-{os.getpid()}",
            "-p", "no:randomly", "--timeout=60",
        ],
        env={**os.environ, "LENS_TRANSPORT_BACKOFF_S": "0"},
    )
    out = (proc.stdout or "") + (proc.stderr or "")
    match = re.search(r"(\d+) passed", out)
    failed = re.search(r"(\d+) failed", out)
    errored = re.search(r"(\d+) error", out)
    summary = ""
    if match:
        summary = f"{match.group(1)} passed"
    if failed:
        summary = (summary + f", {failed.group(1)} failed").lstrip(", ")
    if errored:
        summary = (summary + f", {errored.group(1)} error(s)").lstrip(", ")
    if not summary:
        first_err = next(
            (ln.strip() for ln in out.splitlines()
             if ln.strip() and ("ERROR" in ln or "error:" in ln)),
            "",
        )
        summary = f"pytest exited {proc.returncode}, nothing verified"
        if first_err:
            summary += f": {first_err[:120]}"
    return proc.returncode == 0, summary


def inner_loop(files: list[str]) -> tuple[list[Check], list[Check]]:
    """Map changed modules to their tests, run them, report per-module."""
    inner: list[Check] = []
    guards: list[Check] = []

    src_files = [f for f in files if f.startswith("src/") and f.endswith(".py")]
    test_files = [f for f in files if f.startswith("tests/") and f.endswith(".py")]

    # Two separate claims, kept separate on purpose:
    #   1. coverage CLAIM -- a test names this module (static, instant)
    #   2. measured fact  -- the test files this PR changed actually pass
    # The earlier design ran every test that merely named a changed module:
    # 6 modules x dozens of files, slow enough to time out, and it stamped one
    # combined verdict on all six lines so the report could not say which
    # module failed -- the one thing it exists to say.
    all_tests: list[str] = []
    named_ok = 0
    for module in src_files:
        tests = covering_tests(module)
        all_tests.extend(tests)
        if tests:
            named_ok += 1
            shown = ", ".join(Path(t).name for t in tests[:8])
            more = f" (+{len(tests) - 8} more)" if len(tests) > 8 else ""
            inner.append(Check(module, True, f"→ named by {shown}{more}"))
        else:
            inner.append(Check(module, False, "changed, and no test file names it"))

    if test_files:
        passed, summary = run_tests(test_files)
        inner.append(
            Check(
                "changed tests",
                passed,
                "→ " + ", ".join(Path(t).name for t in test_files)
                + f" — {summary}",
            )
        )
        guards.append(Check("changed tests pass", passed, summary))
    else:
        guards.append(
            Check("changed tests pass", False, "no test files changed in this PR")
        )

    if src_files:
        guards.append(
            Check(
                "every changed module is named by a test",
                named_ok == len(src_files),
                f"{named_ok}/{len(src_files)} module(s), "
                f"{len(set(all_tests))} naming test file(s)",
            )
        )

    # The signal that matters most: a src change with no accompanying test
    # change means the author asserts behaviour they did not pin down.
    if src_files and not test_files:
        guards.append(
            Check(
                "behaviour change is pinned by a test change",
                False,
                f"{len(src_files)} src file(s) changed and 0 test files changed",
            )
        )
    elif src_files:
        guards.append(
            Check(
                "behaviour change is pinned by a test change",
                True,
                f"{len(src_files)} src file(s) and {len(test_files)} test file(s) changed",
            )
        )

    return inner, guards


def build_report(pr: int) -> tuple[Report, str, str]:
    sha, branch = pr_head(pr)
    files = changed_files(pr)
    report = Report()
    report.outer = outer_loop(sha)
    report.inner, report.guards = inner_loop(files)
    return report, sha, branch


def post_comment(pr: int, body: str) -> None:
    """Create or update the single evidence comment on the PR."""
    existing = _gh(
        "pr", "view", str(pr), "--json", "comments",
        "-q", ".comments[] | select(.body | startswith(\"<!-- pr-evidence:generated -->\")) | .id",
    ).strip()
    path = Path(f"/tmp/pr_evidence_{pr}.md")
    path.write_text(body)
    if existing:
        comment_id = existing.splitlines()[0].strip()
        _gh("api", "-X", "PATCH", f"repos/{{owner}}/{{repo}}/issues/comments/{comment_id}",
            "-F", f"body=@{path}")
        print(f"updated comment {comment_id} on #{pr}")
    else:
        _gh("pr", "comment", str(pr), "--body-file", str(path))
        print(f"created evidence comment on #{pr}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("pr", type=int, help="PR number")
    parser.add_argument("--post", action="store_true", help="create/update the PR comment")
    args = parser.parse_args()

    report, sha, branch = build_report(args.pr)
    body = report.render(args.pr, sha, branch)
    print(body)

    if args.post:
        post_comment(args.pr, body)

    return 0 if report.ok() else 1


if __name__ == "__main__":
    sys.exit(main())
